# -*- coding: utf-8 -*-
"""写使用说明到 dist 目录（用 Python 写，避免 PowerShell 破坏 UTF-8）。"""
import os

DST = r"D:\deepseekproject\agedl\dist\AGE下载器\使用说明.txt"

TEXT = """\
════════════════════════════════════════════════════════
  AGE动漫 视频下载器  v1.0
════════════════════════════════════════════════════════

【这是什么】
  从 AGE动漫（age001.com 及同模板站点）的播放页解析 m3u8 源，
  批量下载整集视频并封装成 MP4 / MKV 的桌面工具。
  内置 ffmpeg，无需另外安装任何东西。

【怎么用 GUI】
  1. 在浏览器打开想下的动画播放页，复制地址栏的网址；
  2. 粘贴到软件第 1 栏的地址框，点「解析」（或点「从剪贴板」自动填入）；
  3. 第 2 栏会列出全部线路与集数：
       · 上方下拉框切换线路（不同线路清晰度/完整度不同）；
       · 点某行最左边的 ☑/☐ 勾选该集，或点「全选」「按范围」批量选；
       · 点「探测全部集详情」可看到每集的时长、分辨率、码率、预计大小；
  4. 第 3 栏选输出目录、格式（MP4 或 MKV）、并发数（默认 16，网速快可调 24~32）；
       · 建议保持勾选「自动剔除广告段」；
  5. 点第 4 栏「开始下载」，总进度与单集进度实时显示，下方日志可看细节。

【命令行模式（可选，批量/脚本用）】
  AGE下载器.exe --cli <播放页网址> -n 1-12 -f mp4 -w 24 -o D:\\视频

  参数：
    -n, --episodes   集数，支持 1 / 1-3 / 1,2,5（默认 1）
    -f, --fmt        mp4 或 mkv（默认 mp4）
    -w, --workers    并发分片数（默认 16）
    -o, --out        输出目录（默认 用户目录\\Downloads\\AGE动漫）
    --keep-ads       保留广告段
    --keep-segments  保留分片缓存
  --selftest <网址>  无界面自检，结果写到本目录 selftest.txt

【常见问题】
  Q: 双击没反应？
  A: 本程序是 onedir 结构，exe 必须和旁边的 _internal 文件夹放在一起，
     不要单独把 exe 拷出去。

  Q: 杀毒软件报毒 / 拦截？
  A: PyInstaller 打包的 Python 程序常被误报（360 尤其敏感）。
     把整个文件夹加入白名单即可。

  Q: 下载到一半卡住 / 某集失败？
  A: 日志会标出失败分片，程序会自动串行重试一轮。
     仍失败通常是源站限流，把并发调小（如 -w 8）再试。

  Q: 为什么没有 TS 格式？
  A: 本机某些安全驱动对 .ts 扩展名做透明加密，会导致播放器读到损坏文件，
     所以改用 MKV（同样是流拷贝、无损、体积几乎一样、兼容性更好）。

  Q: 广告没剔干净 / 正片被误删？
  A: 剔除逻辑按「分片来源 CDN」判定，若源站换了 CDN 结构可能失准。
     取消勾选「自动剔除广告段」重下一次即可保留全部内容。

【输出文件】
  默认命名：<剧名> 第NN集.mp4
  下载后可直接用任意播放器打开。
"""

os.makedirs(os.path.dirname(DST), exist_ok=True)
with open(DST, "w", encoding="utf-8-sig", newline="\r\n") as f:
    f.write(TEXT)
print("written:", DST, os.path.getsize(DST), "bytes")
